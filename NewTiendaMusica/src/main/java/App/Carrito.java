    private void importar(Cancion[] carrito) {

        //Importar datos de la tabla
        //Creacion del modelo
        dtm.addColumn("ID");
        dtm.addColumn("Nombre de la cancion");
        dtm.addColumn("Artista");
        dtm.addColumn("Precio");
        tblcarrito.setModel(dtm);

        //Extraccion de datos
        Object[] datos = new Object[4];

        for (int i = 0; i < carrito.length; i++) {
            datos[0] = carrito[i].getId();
            datos[1] = carrito[i].getNombre();
            datos[2] = carrito[i].getArtista();
            datos[3] = carrito[i].getPrecio();
            dtm.addRow(datos);
        }

    }

    private void comprar() {
        String msg = "comprar";
        int portDes = 9000;
        StringBuilder sb= new StringBuilder();
        for(int i=0;i<carrito.length;i++){
            sb.append(carrito[i].getNombre()+"\n");
        }
        String[] lista = sb.toString().split("\n");
        
        InetAddress dst;

        int puerto = 9091;
        try {
            dst = InetAddress.getByName("127.0.0.1");
            DatagramSocket cl = new DatagramSocket(puerto);
            cl.setReuseAddress(true);
            String l = sb.toString();
            byte[] b = l.getBytes();
            DatagramPacket pS = new DatagramPacket(b, b.length, dst, portDes);
            cl.send(pS);
            FileOutputStream fos=null;
            //empezar a recibir paquetes
            for (int i = 0; i < carrito.length; i++) {
                b = new byte[32000];
                fos = new FileOutputStream(path+lista[i]+".mp3");
                int numPack = 0;
                DatagramPacket p1 = new DatagramPacket(b, b.length);
                cl.receive(p1);
                String datos = new String(p1.getData(),0,p1.getLength());
                Long tamTotal = Long.parseLong(datos);
                System.out.println("Numero de paquetes a recibir -> "+tamTotal);
                while(numPack<tamTotal){
                    p1 = new DatagramPacket(b, b.length);
                    System.out.println("Esperando Byte...");
                    cl.receive(p1);
                    numPack++;
                    fos.write(p1.getData(), 0, p1.getLength());
                    System.out.println("Recibido el Byte "+numPack+" de "+tamTotal);
                }
                fos.flush();
            }
            fos.close();
            

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
