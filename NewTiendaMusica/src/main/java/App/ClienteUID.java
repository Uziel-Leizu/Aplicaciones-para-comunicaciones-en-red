    public void ActualizarCancion(){
        album = new ImageIcon(catalogo[j].getImagen());
        AlbumLbl.setIcon(new ImageIcon(album.getImage().getScaledInstance(AlbumLbl.getWidth(), AlbumLbl.getHeight(), Image.SCALE_SMOOTH)));
        lblnombre.setText(catalogo[j].getNombre());
        lblartista.setText(catalogo[j].getArtista());
        lblaño.setText(catalogo[j].getAño());
        lblprecio.setText(String.valueOf(catalogo[j].getPrecio()));
    }
    public Cancion[] pedirCatalogo() {
        String msg = "catalogo";
        int portDes = 9000;
        Cancion[] catalogo = new Cancion[6];

        InetAddress dst;

        int puerto = 9090;
        try {
            dst = InetAddress.getByName("127.0.0.1");
            DatagramSocket cl = new DatagramSocket(puerto);
            cl.setReuseAddress(true);
            byte[] msgBytes = msg.getBytes();
            DatagramPacket pS = new DatagramPacket(msgBytes, msgBytes.length, dst, portDes);
            cl.send(pS);
            System.out.println("Datagrama enviado esperando respuesta...");
            DatagramPacket pE = new DatagramPacket(new byte[32000], 32000);
            cl.receive(pE);
            System.out.println("Tenemos respuesta");
            ObjectInputStream ois = new ObjectInputStream(new ByteArrayInputStream(pE.getData()));
            //Cargado de objetos
            for (int i = 0; i < 6; i++) {
                catalogo[i] = (Cancion) ois.readObject();
                System.out.println("ID: " + catalogo[i].getId());
                System.out.println("Nombre: " + catalogo[i].getNombre());
                System.out.println("\n\n");

            } //for
            return catalogo;
        } catch (Exception e) {
            e.printStackTrace();
            catalogo=null;
            return catalogo;
        }
    }

