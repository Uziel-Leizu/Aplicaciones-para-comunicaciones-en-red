    private void btncatalogoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncatalogoActionPerformed
       /* band=1;
        if(band==1){
            btncatalogo.setText("Catalogo enviado");
            btncatalogo.setEnabled(false);
        }
        
        */
        misCanciones= new Cancion[13];
        canciones= new GestionCancion(misCanciones);
        
       misCanciones=canciones.generarCanciones(); 
        
       //Comprobar que se han cargado correctamente
        System.out.println("Canciones cargadas");
        for(int i=0;i<misCanciones.length;i++){
            System.out.println("Nombre: "+misCanciones[i].getNombre()+" "+"\nDuración: "+misCanciones[i].getDuracion()+"\n\n");
        }
        
        //Enviar al cliente
        try {
            
            int puerto=9190;
            int puertodest=9090;
            
            InetAddress dst = InetAddress.getByName("localhost");
            DatagramSocket s = new DatagramSocket(puerto);
            s.setReuseAddress(true);
            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            ObjectOutputStream oos = new ObjectOutputStream(baos);
            
 
            
          //Escritura de objeto para datagrama
          for(int i=0;i<13;i++){
           oos.writeObject(misCanciones[i]);
           oos.flush();  
          } //for
            
          //Envio de datagrama
            byte[] b2 = baos.toByteArray();
            DatagramPacket dp = new DatagramPacket(b2,b2.length,dst,puertodest);
            s.send(dp);
    
            s.close();
            
            
        } catch (SocketException ex) {
            ex.printStackTrace();
        } catch (IOException ex) {
            ex.printStackTrace();
        }
        
        
    }//GEN-LAST:event_btncatalogoActionPerformed

