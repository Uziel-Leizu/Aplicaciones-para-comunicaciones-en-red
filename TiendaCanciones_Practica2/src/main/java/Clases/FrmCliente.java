    private void flderMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_flderMouseClicked
       
        j++;
        
        //Regresar indice
        if(j>12)
            j=0;
        
        //Comprobacion de estado
        if(add[j]==true){
            btnadd.setText("Añadida al carrito");
            btnadd.setEnabled(false);  
        }else{
            btnadd.setText("Agregar al carrito");
            btnadd.setEnabled(true);
        }        
        
        //Poner los datos en la GUI
        album = new ImageIcon(miscanciones[j].getImagen());
        lblalbum.setIcon(new ImageIcon(album.getImage().getScaledInstance(lblalbum.getWidth(), lblalbum.getHeight(), Image.SCALE_SMOOTH)));
        
        lblnombre.setText(miscanciones[j].getNombre());
        lblartista.setText(miscanciones[j].getArtista());
        lblduracion.setText(miscanciones[j].getDuracion());
        lblaño.setText(miscanciones[j].getAño());
        lblprecio.setText(String.valueOf(miscanciones[j].getPrecio()));  
        
        
    }//GEN-LAST:event_flderMouseClicked

