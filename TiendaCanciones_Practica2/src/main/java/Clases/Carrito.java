    //Traspaso de bytes
    private byte[] readFileToByteArray(File file) {
        FileInputStream fis = null;
        byte[] bArray = new byte[(int) file.length()];
        try {
            fis = new FileInputStream(file);
            fis.read(bArray);
            fis.close();

        } catch (IOException ioExp) {
            ioExp.printStackTrace();
        }
        return bArray;

    }

    private static void sendFile(DatagramSocket socket, byte[] fileByteArray, InetAddress address, int port) throws IOException {
        System.out.println("Sending file");
        int sequenceNumber = 0; // Secuencia
        boolean flag; // Bandera fin datagrama
        int ackSequence = 0; // Bandera de ¿datagrama recibido?

        for (int i = 0; i < fileByteArray.length; i = i + 1021) {
            sequenceNumber += 1;

          
            byte[] message = new byte[1024]; // 
            message[0] = (byte) (sequenceNumber >> 8);
            message[1] = (byte) (sequenceNumber);
            
            //Comprobar estado de datagrama
            if ((i + 1021) >= fileByteArray.length) { 
                flag = true;
                message[2] = (byte) (1); 
            } else {
                flag = false;
                message[2] = (byte) (0); 
            }

            if (!flag) {
                System.arraycopy(fileByteArray, i, message, 3, 1021);
            } else { 
                System.arraycopy(fileByteArray, i, message, 3, fileByteArray.length - i);
            }

            DatagramPacket sendPacket = new DatagramPacket(message, message.length, address, port); 
            socket.send(sendPacket); 
            System.out.println("Sent: Sequence number = " + sequenceNumber);

            boolean ackRec; 

            while (true) {
                byte[] ack = new byte[2]; 
                DatagramPacket ackpack = new DatagramPacket(ack, ack.length);

                try {
                    socket.setSoTimeout(50); 
                    socket.receive(ackpack);
                    ackSequence = ((ack[0] & 0xff) << 8) + (ack[1] & 0xff); 
                    ackRec = true; 
                } catch (SocketTimeoutException e) {
                    System.out.println("Tiempo de espera");
                    ackRec = false; 
                }

               
                if ((ackSequence == sequenceNumber) && (ackRec)) {
                    System.out.println("Datagrama recibido, secuencia: " + ackSequence);
                    break;
                } 
                else {
                    socket.send(sendPacket);
                    System.out.println("Reenvio,secuencia: " + sequenceNumber);
                }
            }
        }
    }
    
